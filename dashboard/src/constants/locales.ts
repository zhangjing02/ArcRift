export function getNodeTypeLabel(type: string, locale: Locale = "zh"): string {
  if (!type) return locale === "zh" ? "未分类" : "Uncategorized";
  const item = ENTITY_TYPE_TRANSLATIONS[type];
  if (item) {
    return locale === "zh" ? item.zh : item.en;
  }
  return type;
}

export function getNodeTypeAbbr(type: string, locale: Locale = "zh"): string {
  if (!type) return "";
  const item = ENTITY_TYPE_TRANSLATIONS[type];
  if (item) {
    return locale === "zh" ? item.abbrZh : item.abbrEn;
  }
  return type.slice(0, 4).toUpperCase();
}
